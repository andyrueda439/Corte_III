CREATE DATABASE bdlaboratorioorm;

--parte B
CREATE SCHEMA IF NOT EXISTS laboratorio;

CREATE TABLE laboratorio.tipo_equipo (
                                         id_tipo     BIGINT GENERATED BY DEFAULT AS IDENTITY,
                                         nombre      VARCHAR(100) NOT NULL,
                                         descripcion VARCHAR(250),
                                         CONSTRAINT pk_tipo_equipo        PRIMARY KEY (id_tipo),
                                         CONSTRAINT uq_tipo_equipo_nombre UNIQUE (nombre)
);

CREATE TABLE laboratorio.equipo (
                                    id_equipo BIGINT GENERATED BY DEFAULT AS IDENTITY,
                                    codigo    VARCHAR(30)  NOT NULL,
                                    nombre    VARCHAR(120) NOT NULL,
                                    marca     VARCHAR(80),
                                    estado    VARCHAR(30)  NOT NULL,
                                    cantidad  INTEGER      NOT NULL DEFAULT 1,
                                    id_tipo   BIGINT       NOT NULL,
                                    CONSTRAINT pk_equipo        PRIMARY KEY (id_equipo),
                                    CONSTRAINT uq_equipo_codigo UNIQUE (codigo),
                                    CONSTRAINT chk_equipo_cantidad CHECK (cantidad >= 0),
                                    CONSTRAINT chk_equipo_estado
                                        CHECK (estado IN ('Disponible', 'En mantenimiento', 'Fuera de servicio')),
                                    CONSTRAINT fk_equipo_tipo FOREIGN KEY (id_tipo)
                                        REFERENCES laboratorio.tipo_equipo (id_tipo)
                                        ON DELETE RESTRICT
);

CREATE INDEX idx_equipo_id_tipo ON laboratorio.equipo (id_tipo);

